CREATE TABLE IF NOT EXISTS `ai_agent_trace` (
    `id`            BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    `trace_id`      VARCHAR(64)  NOT NULL COMMENT '追踪ID',
    `session_id`    BIGINT       COMMENT '会话ID',
    `user_id`       BIGINT       COMMENT '用户ID',
    `step_type`     VARCHAR(30)  NOT NULL COMMENT '步骤类型：llm_request/llm_response/tool_call/tool_result/chat_start/chat_end',
    `step_name`     VARCHAR(100) COMMENT '步骤名称',
    `input`         TEXT         COMMENT '入参摘要',
    `output`        TEXT         COMMENT '出参摘要',
    `tokens_used`   INT          DEFAULT 0 COMMENT 'LLM token消耗',
    `latency_ms`    BIGINT       DEFAULT 0 COMMENT '耗时(毫秒)',
    `status`        VARCHAR(20)  DEFAULT 'success' COMMENT '状态：success/error',
    `error_msg`     TEXT         COMMENT '错误信息',
    `create_by`     VARCHAR(64)  DEFAULT '' COMMENT '创建者',
    `create_time`   DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_by`     VARCHAR(64)  DEFAULT '' COMMENT '更新者',
    `update_time`   DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_trace_id` (`trace_id`),
    KEY `idx_session_id` (`session_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI Agent 链路追踪';
